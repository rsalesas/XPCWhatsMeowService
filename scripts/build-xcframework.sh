#!/bin/bash
# Builds Go/wabridge (whatsmeow behind a C ABI) into Frameworks/CWhatsMeow.xcframework:
# one universal (arm64 + x86_64) static library plus a module map, so SwiftPM's
# binaryTarget and Xcode both import it as `CWhatsMeow`.
#
# Static, not a dylib: it links into the XPC service's own binary — the one process that
# contains whatsmeow — so there is no extra Mach-O to sign, notarize or embed.
#
# The output is not checked in (it is ~40 MB and fully reproducible). Run this once
# after cloning, and again whenever Go/wabridge or its go.sum changes. It is a no-op
# when the xcframework is newer than every input, so build scripts may call it freely.
#
# Usage: scripts/build-xcframework.sh [--force]

set -euo pipefail

PACKAGE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$PACKAGE_DIR/Go/wabridge"
OUT="$PACKAGE_DIR/Frameworks/CWhatsMeow.xcframework"
WORK="$PACKAGE_DIR/.build/go"
# Must not exceed the app's deployment target, or the linker warns about every object.
MACOS_MIN="14.0"

FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1

if [[ $FORCE -eq 0 && -d "$OUT" ]]; then
    newer=$(find "$SRC" -type f \( -name '*.go' ! -name '*_test.go' -o -name '*.h' -o -name 'go.mod' -o -name 'go.sum' \) -newer "$OUT" | head -1)
    if [[ -z "$newer" ]]; then
        echo "CWhatsMeow.xcframework is up to date."
        exit 0
    fi
fi

# Xcode build phases run with a minimal PATH; find Go where it is usually installed.
if ! command -v go >/dev/null 2>&1; then
    for candidate in /usr/local/go/bin /opt/homebrew/bin "$HOME/go/bin" "$HOME/sdk/go/bin"; do
        if [[ -x "$candidate/go" ]]; then
            export PATH="$candidate:$PATH"
            break
        fi
    done
fi
command -v go >/dev/null 2>&1 || {
    echo "error: Go is not installed. Install it from https://go.dev/dl/ and run WhatsMeowBridge/scripts/build-xcframework.sh." >&2
    exit 1
}
# go.mod asks for a newer toolchain than many machines have; let Go fetch it.
export GOTOOLCHAIN="${GOTOOLCHAIN:-auto}"

rm -rf "$WORK"
mkdir -p "$WORK/arm64" "$WORK/amd64" "$WORK/universal" "$WORK/headers"

SDK="$(xcrun --sdk macosx --show-sdk-path)"
CLANG="$(xcrun --sdk macosx --find clang)"

build_arch() {
    local goarch="$1" clangarch="$2"
    echo "Building wabridge for $clangarch…"
    (
        cd "$SRC"
        CGO_ENABLED=1 GOOS=darwin GOARCH="$goarch" \
        CC="$CLANG -arch $clangarch -isysroot $SDK -mmacosx-version-min=$MACOS_MIN" \
        CGO_CFLAGS="-mmacosx-version-min=$MACOS_MIN" \
        CGO_LDFLAGS="-mmacosx-version-min=$MACOS_MIN" \
        go build -buildmode=c-archive -trimpath -ldflags="-s -w" \
            -o "$WORK/$goarch/libwabridge.a" .
    )
}

build_arch arm64 arm64
build_arch amd64 x86_64

lipo -create "$WORK/arm64/libwabridge.a" "$WORK/amd64/libwabridge.a" \
    -output "$WORK/universal/libwabridge.a"

# Ship the hand-written header, not cgo's generated one: it is the documented contract,
# it has no Go-internal typedefs, and it marks input strings const.
cp "$SRC/wabridge.h" "$WORK/headers/wabridge.h"
cat > "$WORK/headers/module.modulemap" <<'EOF'
module CWhatsMeow {
    header "wabridge.h"
    link "resolv"
    link framework "CoreFoundation"
    link framework "Security"
    export *
}
EOF

# Every module linked into the library, with its licence text, for the service bundle to
# ship (MIT, BSD, ISC and Apache all require the notice to travel with the binary). Written
# into the source tree and committed, so a change in go.sum shows up in review as a
# change in what the service ships.
LICENSES="$PACKAGE_DIR/XPCService/Licenses/ThirdPartyLicenses.txt"
(
    cd "$SRC"
    echo "Third-party software linked into XPCWhatsMeowService."
    echo "Generated by scripts/build-xcframework.sh from Go/wabridge/go.sum — do not edit."
    go list -deps -f '{{if not .Standard}}{{if .Module}}{{.Module.Path}} {{.Module.Version}}{{end}}{{end}}' . \
        | sort -u | while read -r module version; do
            [[ -z "$version" ]] && continue   # this module itself
            dir="$(go list -m -f '{{.Dir}}' "$module")"
            file="$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' \) | sort | head -1)"
            printf '\n\n================================================================\n%s %s\n================================================================\n\n' "$module" "$version"
            if [[ -n "$file" ]]; then cat "$file"; else echo "(no licence file found in the module)"; fi
        done
    # The Go runtime and standard library are linked in too.
    printf '\n\n================================================================\nGo %s (runtime and standard library)\n================================================================\n\n' "$(go env GOVERSION)"
    cat "$(go env GOROOT)/LICENSE"
) > "$LICENSES"

rm -rf "$OUT"
mkdir -p "$(dirname "$OUT")"
xcodebuild -create-xcframework \
    -library "$WORK/universal/libwabridge.a" \
    -headers "$WORK/headers" \
    -output "$OUT" >/dev/null

echo "Built $OUT ($(du -sh "$OUT" | cut -f1))"
